/** The `private:` members line up in a column; the block-visual lesson depends on it. */
export const ringBufferCpp = [
  '#ifndef ENGINE_RING_BUFFER_H_',
  '#define ENGINE_RING_BUFFER_H_',
  '',
  '#include <cstddef>',
  '#include <stdexcept>',
  '#include <vector>',
  '',
  '#include "engine/frame.h"',
  '',
  'namespace engine {',
  '',
  'template <typename T>',
  'class RingBuffer {',
  ' public:',
  '  explicit RingBuffer(std::size_t capacity)',
  '      : data_(capacity), head_(0), size_(0) {}',
  '',
  '  void push(const T& value) {',
  '    if (size_ == data_.size()) {',
  '      throw std::runtime_error("ring buffer is full");',
  '    }',
  '    data_[head_] = value;',
  '    head_ = (head_ + 1) % data_.size();',
  '    ++size_;',
  '  }',
  '',
  '  void fill(const std::vector<T>& values) {',
  '    for (const T& value : values) {',
  '      push(value);',
  '    }',
  '  }',
  '',
  '  std::size_t size() const { return size_; }',
  '  bool empty() const { return size_ == 0; }',
  '',
  ' private:',
  '  std::vector<T> data_;',
  '  std::size_t head_;',
  '  std::size_t size_;',
  '};',
  '',
  'using FrameRing = RingBuffer<Frame>;',
  '',
  '}  // namespace engine',
  '',
  '#endif  // ENGINE_RING_BUFFER_H_',
].join('\n');
