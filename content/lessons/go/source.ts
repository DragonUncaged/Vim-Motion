/** Tabs are written as `\t` and the `Session` columns are gofmt-aligned: goals count columns, and a tab is one. */
export const storeGo = [
  'package store',
  '',
  'import (',
  '\t"context"',
  '\t"errors"',
  '\t"fmt"',
  '\t"time"',
  ')',
  '',
  '// ErrNotFound is returned when no live session matches the id.',
  'var ErrNotFound = errors.New("store: session not found")',
  '',
  'type Session struct {',
  '\tID        string',
  '\tUserID    string',
  '\tToken     string',
  '\tExpiresAt time.Time',
  '}',
  '',
  'type Store struct {',
  '\tcache map[string]*Session',
  '\tttl   time.Duration',
  '}',
  '',
  'func New(ttl time.Duration, size int) *Store {',
  '\treturn &Store{',
  '\t\tcache: make(map[string]*Session, size),',
  '\t\tttl:   ttl,',
  '\t}',
  '}',
  '',
  'func (s *Store) Get(ctx context.Context, id string) (*Session, error) {',
  '\tsess, ok := s.cache[id]',
  '\tif !ok {',
  '\t\treturn nil, ErrNotFound',
  '\t}',
  '\treturn sess, nil',
  '}',
  '',
  'func (s *Store) Rotate(ctx context.Context, id string, now time.Time) error {',
  '\tsess, err := s.Get(ctx, id)',
  '\tif err != nil {',
  '\t\treturn fmt.Errorf("rotate %s: %w", id, err)',
  '\t}',
  '',
  '\ttoken, err := newToken(sess.UserID, now)',
  '\tif err != nil {',
  '\t\treturn fmt.Errorf("rotate token for %s: %w", id, err)',
  '\t}',
  '',
  '\tsess.Token = token',
  '\tsess.ExpiresAt = now.Add(s.ttl)',
  '\treturn nil',
  '}',
].join('\n');
