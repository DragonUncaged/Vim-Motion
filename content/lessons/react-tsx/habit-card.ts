export const habitCard: string = [
  'import { useCallback, useEffect, useState } from "react";',
  'import type { Habit } from "../types/habit";',
  '',
  'interface HabitCardProps {',
  '  habit: Habit;',
  '  onToggle: (id: string, done: boolean) => void;',
  '}',
  '',
  'export function HabitCard({ habit, onToggle }: HabitCardProps) {',
  '  const [streak, setStreak] = useState(habit.streak);',
  '  const [flashing, setFlashing] = useState(false);',
  '',
  '  useEffect(() => {',
  '    setStreak(habit.streak);',
  '  }, [habit.streak]);',
  '',
  '  useEffect(() => {',
  '    if (!flashing) return;',
  '    const timer = window.setTimeout(() => setFlashing(false), 600);',
  '    return () => window.clearTimeout(timer);',
  '  }, [flashing]);',
  '',
  '  const toggle = useCallback(() => {',
  '    setStreak((n) => (habit.done ? n - 1 : n + 1));',
  '    setFlashing(true);',
  '    onToggle(habit.id, !habit.done);',
  '  }, [onToggle, habit.id, habit.done]);',
  '',
  '  return (',
  '    <article className="card soft">',
  '      <header className="card-head">',
  '        <span className="title">{habit.name}</span>',
  '        <span className="streak">{streak} days</span>',
  '      </header>',
  '      <button',
  '        className={flashing ? "toggle flash" : "toggle"}',
  '        onClick={() => toggle()}',
  '      >',
  '        {habit.done ? "Done" : "Mark done"}',
  '      </button>',
  '    </article>',
  '  );',
  '}',
].join('\n');
