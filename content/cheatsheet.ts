/** The reference behind `/cheatsheet`; `keys` are written in docs/CONTRACT.md §5 notation. */

import type { ClayHue } from './types';

export type CheatAccent = ClayHue;

export interface CheatEntry {
  /** Unique across the sheet and stable: it keys keyboard navigation and the anchors. */
  id: string;
  /** The keys, in docs/CONTRACT.md §5 notation: `dw`, `ci<lt>`, `<C-d>`, `f<char>`. */
  keys: string;
  /** One line, no full stop, in the words someone would use out loud. */
  desc: string;
  /** As in `Exercise.motions`; the bare form (`f`, `dt`) where the target character is incidental. */
  motion?: string;
  tags?: string[];
  /** A gotcha or a reason, only where it earns the line; docs/CONTRACT.md §5 markup allowed. */
  note?: string;
  tasks?: string[];
}

export interface CheatGroup {
  id: string;
  title: string;
  blurb: string;
  accent: CheatAccent;
  entries: CheatEntry[];
}

export interface CheatTask {
  id: string;
  /** Phrased as the intention, not the key: "change something inside delimiters". */
  title: string;
  blurb: string;
  accent: CheatAccent;
}

