export const allCheats: CheatEntry[] = cheatGroups.flatMap((g) => g.entries);

function assertSheetIsSound(): void {
  const taskIds = new Set(cheatTasks.map((t) => t.id));
  const seen = new Set<string>();
  for (const entry of allCheats) {
    if (seen.has(entry.id)) {
      throw new Error(`Duplicate cheatsheet entry id "${entry.id}".`);
    }
    seen.add(entry.id);
    for (const task of entry.tasks ?? []) {
      if (!taskIds.has(task)) {
        throw new Error(
          `Cheatsheet entry "${entry.id}" names task "${task}", which does not exist.`,
        );
      }
    }
  }
  const groupIds = new Set<string>();
  for (const group of cheatGroups) {
    if (groupIds.has(group.id)) throw new Error(`Duplicate cheatsheet group id "${group.id}".`);
    groupIds.add(group.id);
  }
}

assertSheetIsSound();
